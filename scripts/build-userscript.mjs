#!/usr/bin/env node
// Bundles src/header.js + src/score.js + src/userscript.js + data/games.json into
// dist/xbox-cloud-scores.user.js (installable in Tampermonkey) and the matching .meta.js
// that Tampermonkey polls for updates.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");

const pkg = JSON.parse(read("package.json"));
const { meta, games } = JSON.parse(read("data/games.json"));

// Version: <major>.<minor>.<data build date>.<data build time>, so every data refresh is an update.
const built = new Date(meta.builtAt);
const pad = (n) => String(n).padStart(2, "0");
const stamp = `${built.getUTCFullYear()}${pad(built.getUTCMonth() + 1)}${pad(built.getUTCDate())}.${pad(built.getUTCHours())}${pad(built.getUTCMinutes())}`;
const [major, minor] = pkg.version.split(".");
const version = `${major}.${minor}.${stamp}`;

// ---- compact data: one shared string table + one array per game
const strings = [];
const strIndex = new Map();
const S = (s) => {
  if (!s) return -1;
  if (!strIndex.has(s)) {
    strIndex.set(s, strings.length);
    strings.push(s);
  }
  return strIndex.get(s);
};

const FLAG = { gamePass: 1, byog: 2, f2p: 4, ads: 8, recent: 16, leaving: 32, adsOwn: 64 };
const INPUT = { controller: 1, mkb: 2, touch: 4 };
const MODE = { single: 1, "online-mp": 2, "local-mp": 4, "online-coop": 8, "local-coop": 16, crossplay: 32 };

const rows = games.map((g) => [
  g.id,
  g.title,
  S(g.publisher),
  S(g.developer),
  g.genres.map(S),
  g.release ? Number(g.release.replace(/-/g, "")) : 0,
  g.age ?? -1,
  g.inputs.reduce((m, k) => m | (INPUT[k] || 0), 0),
  g.modes.reduce((m, k) => m | (MODE[k] || 0), 0),
  Object.entries(FLAG).reduce((m, [k, bit]) => m | (g[k] ? bit : 0), 0),
  g.popularity || 0,
  g.price == null ? -1 : Math.round(g.price * 100),
  g.image || "",
  g.store ? Math.round(g.store.rating * 10) : 0,
  g.store ? g.store.count : 0,
  g.steam ? g.steam.appid : 0,
  g.steam ? g.steam.positive : 0,
  g.steam ? g.steam.total : 0,
  g.metacritic || 0,
  g.score ?? -1,
  g.confidence || 0,
]);

const data = { v: 1, builtAt: meta.builtAt, market: meta.market, strings, rows };

const header = read("src/header.js")
  .replace("{{VERSION}}", version)
  .replace(
    "{{DATA_INFO}}",
    `${meta.count} games, built ${meta.builtAt} for market ${meta.market} (store ratings ${meta.withStore}, Steam ${meta.withSteam}, Metacritic ${meta.withMetacritic})`
  );
const score = read("src/score.js").replace(/^export\s+/gm, "");
const body = read("src/userscript.js");

const out = `${header}
(function () {
  "use strict";

// ---------------------------------------------------------------- src/score.js
${score}
// ---------------------------------------------------------------- src/userscript.js
${body}
// ---------------------------------------------------------------- bundled data (generated by scripts/fetch-data.mjs)
function xcsData() {
  return ${JSON.stringify(data)};
}
})();
`;

const dist = path.join(ROOT, "dist");
fs.mkdirSync(dist, { recursive: true });
fs.writeFileSync(path.join(dist, "xbox-cloud-scores.user.js"), out);
fs.writeFileSync(path.join(dist, "xbox-cloud-scores.meta.js"), header.split("// ==/UserScript==")[0] + "// ==/UserScript==\n");

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
console.log(`dist/xbox-cloud-scores.user.js  v${version}  ${kb(Buffer.byteLength(out))}  (${rows.length} games, ${strings.length} strings)`);
